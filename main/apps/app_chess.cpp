    void build_ui(lv_obj_t *root)
    {
        lv_obj_t *title = lv_label_create(root);
        lv_label_set_text(title, "Chess");
        lv_obj_set_style_text_font(title, &lv_font_montserrat_16, 0);
        lv_obj_set_style_text_color(title, lv_color_hex(BadgeTheme::TEXT), 0);
        lv_obj_align(title, LV_ALIGN_TOP_LEFT, kBoardX, 4);

        // 64 cells and 64 labels, created once and thereafter only restyled.
        // Creating and destroying widgets as pieces move would churn the LVGL
        // heap on every ply; app_tetris.cpp:242-262 sets the precedent.
        for (int cell = 0; cell < 64; ++cell) {
            int row = cell >> 3, col = cell & 7;
            lv_obj_t *c = lv_obj_create(root);
            lv_obj_remove_style_all(c);
            lv_obj_set_size(c, kCell, kCell);
            lv_obj_set_pos(c, kBoardX + col * kCell, kBoardY + row * kCell);
            lv_obj_set_style_bg_opa(c, LV_OPA_COVER, 0);
            lv_obj_set_style_radius(c, 0, 0);
            lv_obj_clear_flag(c, LV_OBJ_FLAG_SCROLLABLE);

            lv_obj_t *l = lv_label_create(c);
            lv_obj_set_style_text_font(l, cell_font(), 0);
            lv_obj_center(l);
            lv_label_set_text(l, "");

            cells_[cell]  = c;
            labels_[cell] = l;
        }

        turn_lbl_ = panel_label(root, 0, &lv_font_montserrat_16);
        result_lbl_ = panel_label(root, 22, &lv_font_montserrat_14);
        last_lbl_ = panel_label(root, 44, &lv_font_montserrat_14);
        score_lbl_ = panel_label(root, 66, &lv_font_montserrat_14);

        hint_ = lv_label_create(root);
        lv_obj_set_style_text_font(hint_, &lv_font_montserrat_14, 0);
        lv_obj_set_style_text_color(hint_, lv_color_hex(BadgeTheme::TEXT_MUTED), 0);
        lv_obj_align(hint_, LV_ALIGN_BOTTOM_LEFT, kBoardX, -4);

        build_menu(root);
    }

