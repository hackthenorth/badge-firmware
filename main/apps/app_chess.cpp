// Chess. Two badges over the radio eventually; for now one badge, hot seat.
//
// The rules live in chess_rules.cpp and are verified on a host against the
// standard perft suite (tools/chess-perft), so nothing in this file has any
// business deciding what a legal move is. This is a view and an input state
// machine, the way app_sync.cpp is a view over bbx_xfer.
//
// Board geometry is chosen around the one hard constraint: 240 px of height
// has to hold a title bar, eight ranks and a hint line. 24 px cells give a
// 192 px board, which leaves 108 px of side panel — enough for the turn, the
// result and a move list, and wide enough that nothing has to be abbreviated.

