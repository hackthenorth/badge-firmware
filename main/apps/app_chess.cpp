// --- console surface --------------------------------------------------------
//
// The REPL runs on its own task. Every entry point below takes the LVGL lock,
// because it mutates state that the 50 Hz tick and the render path both touch.

size_t chess_app_debug(char *out, size_t out_sz)
{
    if (out_sz) out[0] = '\0';
    lvgl_port_lock(0);
    size_t n = ChessApp::s_active ? ChessApp::s_active->debug(out, out_sz) : 0;
    lvgl_port_unlock();
    return n;
}

bool chess_app_set_fen(const char *fen)
{
    lvgl_port_lock(0);
    bool ok = ChessApp::s_active && ChessApp::s_active->set_fen(fen);
    lvgl_port_unlock();
    return ok;
}

bool chess_app_play_uci(const char *uci)
{
    lvgl_port_lock(0);
    bool ok = ChessApp::s_active && ChessApp::s_active->play_uci(uci);
    lvgl_port_unlock();
    return ok;
}

bool chess_app_new_game()
{
    lvgl_port_lock(0);
    bool ok = ChessApp::s_active != nullptr;
    if (ok) { ChessApp::s_active->new_game(); }
    lvgl_port_unlock();
    return ok;
}

bool chess_app_bump()
{
    lvgl_port_lock(0);
    bool ok = ChessApp::s_active != nullptr;
    if (ok) ChessApp::s_active->bump();
    lvgl_port_unlock();
    return ok;
}

bool chess_app_flip()
{
    lvgl_port_lock(0);
    bool ok = ChessApp::s_active != nullptr;
    if (ok) ChessApp::s_active->flip();
    lvgl_port_unlock();
    return ok;
}

bool chess_app_perft(int depth, uint64_t *out_nodes, uint32_t *out_ms)
{
    if (depth < 1) depth = 1;

    // Snapshot under the lock, then let it go. Perft at depth 4 is seconds of
    // work at 80 MHz; holding the LVGL lock across it would freeze the panel
    // and stall the registry's tick.
    lvgl_port_lock(0);
    bool active = ChessApp::s_active != nullptr;
    ChessPos pos{};
    if (active) pos = ChessApp::s_active->position_copy();
    lvgl_port_unlock();
    if (!active) return false;

    // Heap, not stack: CH_MAX_MOVES * 4 moves is 1744 bytes, and the console
    // task has no room to spare for it.
    ChessMove *scratch = (ChessMove *)malloc(sizeof(ChessMove) * CH_MAX_MOVES * (size_t)depth);
    if (!scratch) return false;

    int64_t t0 = esp_timer_get_time();
    uint64_t nodes = chess_perft(&pos, depth, scratch);
    int64_t t1 = esp_timer_get_time();
    free(scratch);

    if (out_nodes) *out_nodes = nodes;
    if (out_ms) *out_ms = (uint32_t)((t1 - t0) / 1000);
    return true;
}
