// LEGACY — this is the JLC assembly-line test script. It is kept around
// deliberately, but it is not the path attendee badges or developers take:
// reach for app_test.cpp instead. Changes here should be limited to keeping
// it compiling unless the factory run genuinely needs them.
//
// Factory hardware test — an alternative, dead-simple main flow for the
// assembly line in China. It is always compiled but only runs when the
// `factory.enabled` config flag is set (see main.cpp); when it does, it takes
// over the whole device on boot instead of the normal launcher.
//
// Unlike app_test.cpp (the developer bring-up checklist that lives in the
// launcher), this:
//   * is bilingual (English + Chinese) for factory operators,
//   * installs its OWN button dispatcher so it captures all buttons,
//     including HOME (the registry would otherwise eat HOME as "home"),
//   * shows a persistent colored status strip on every screen, so any single
//     photo sent back from the line tells you exactly what passed / failed.
//
// All Chinese glyphs are rendered from font_cjk_18, a tiny subset font
// generated by tools/image-convert/gen-cjk-font.sh. If you change a Chinese
// string here, re-run that script and keep its SYMBOLS list in sync.

#include "hal_display.h"
#include "hal_buttons.h"
#include "hal_lights.h"
#include "hal_nfc.h"
#include "hal_accel.h"

#include "esp_lvgl_port.h"
#include "lvgl.h"

#include <cmath>
#include <cstdio>
#include <cstring>

// Generated by gen-cjk-font.sh (C linkage — it's a .c file).
extern "C" const lv_font_t font_cjk_18;
// Existing 48x48 NFC icon from the icon pipeline.
extern "C" const lv_image_dsc_t icon_nfc;

namespace {

// Shared palette (mirrors app_test.cpp / the summary so the strip and the
// final screen read consistently).
constexpr uint32_t COL_PASS     = 0x00a050; // green
constexpr uint32_t COL_FAIL     = 0xd23b3b; // red
constexpr uint32_t COL_UNTESTED = 0x6a7a9a; // gray
constexpr uint32_t COL_PENDING  = 0x1a2332; // dim
constexpr uint32_t COL_CURRENT  = 0x00d9ff; // cyan (current-step outline)
constexpr uint32_t COL_BORDER   = 0x2d4a6b; // idle border
constexpr uint32_t COL_TEXT     = 0xe0e8f0; // off-white

enum class Res : uint8_t { Pending, Pass, Fail, Untested };

// Category indices into result_[]. Only the first three (CAT_BTN..CAT_NFC) are
// interactive stages shown in the status strip; CAT_ACC and CAT_RC522 are
// hidden checks judged passively and reported only on the summary.
enum Cat : int { CAT_BTN = 0, CAT_LED, CAT_NFC, CAT_ACC, CAT_RC522, CAT_COUNT };

enum class Step { Buttons, Leds, Nfc, Summary };

uint32_t color_for(Res r)
{
    switch (r) {
        case Res::Pass:     return COL_PASS;
        case Res::Fail:     return COL_FAIL;
        case Res::Untested: return COL_UNTESTED;
        default:            return COL_PENDING;
    }
}

lv_obj_t *make_label(lv_obj_t *parent, const lv_font_t *font, uint32_t color, const char *txt)
{
    lv_obj_t *l = lv_label_create(parent);
    lv_obj_set_style_text_font(l, font, 0);
    lv_obj_set_style_text_color(l, lv_color_hex(color), 0);
    lv_label_set_text(l, txt);
    return l;
}

class FactoryTest {
public:
    void run()
    {
        // Same infra app_registry_start sets up, but standalone: a 20ms tick
        // timer + our own button dispatcher. Both run in the LVGL task (the
        // dispatcher is drained by an lv_timer in hal_buttons), so on_tick /
        // on_button may touch LVGL without extra locking.
        root_ = hal_display_root();
        if (!root_) return;

        lvgl_port_lock(0);
        lv_obj_clean(root_);
        tick_timer_ = lv_timer_create(tick_cb, 20, nullptr);
        step_ = Step::Buttons;
        reset_state();
        build_step_ui();
        lvgl_port_unlock();

        hal_buttons_set_dispatcher([](ButtonEvent e) { instance().on_button(e); });
    }

    static FactoryTest &instance()
    {
        static FactoryTest s;
        return s;
    }

private:
    static void tick_cb(lv_timer_t *) { instance().on_tick(); }

    void reset_state()
    {
        for (auto &r : result_) r = Res::Pending;
        memset(buttons_seen_, 0, sizeof(buttons_seen_));
        lights_tick_ = 0;
        led_phase_shown_ = -1;
        led_cycle_done_ = false;
        nfc_enabled_ = false;
        accel_reads_ = 0;
        accel_reasonable_ = accel_moved_ = false;
        for (int i = 0; i < 3; i++) { accel_min_[i] = 1e9f; accel_max_[i] = -1e9f; }
        nfc_chip_probed_ = false;
        nfc_chip_version_ = 0;
    }

    // ---- input -------------------------------------------------------------

    void on_button(ButtonEvent ev)
    {
        if (ev.kind != ButtonEventKind::Pressed) return;
        switch (step_) {
            case Step::Buttons: handle_button_pad(ev.button); break;
            case Step::Leds:
                if (!led_cycle_done_) break; // wait for one full color cycle
                if (ev.button == Button::A) { result_[CAT_LED] = Res::Pass; advance(); }
                else if (ev.button == Button::B) { result_[CAT_LED] = Res::Fail; advance(); }
                break;
            case Step::Nfc:
                if (ev.button == Button::A) { result_[CAT_NFC] = Res::Untested; advance(); }
                break;
            case Step::Summary:
                if (ev.button == Button::A) { step_ = Step::Buttons; reset_state(); build_step_ui(); }
                break;
        }
    }

    void on_tick()
    {
        sample_accel();             // sampled on every screen
        probe_nfc_chip();           // one-shot reader-IC handshake
        if (step_ == Step::Leds)  tick_leds();
        if (step_ == Step::Nfc)   tick_nfc();
        update_strip();
    }

    void advance()
    {
        switch (step_) {
            case Step::Buttons: step_ = Step::Leds;    break;
            case Step::Leds:    step_ = Step::Nfc;     break;
            case Step::Nfc:     step_ = Step::Summary; break;
            case Step::Summary: return;
        }
        build_step_ui();
    }

    // ---- accelerometer (no screen; judged from continuous sampling) --------

    void sample_accel()
    {
        AccelSample s;
        if (hal_accel_read(&s) != ESP_OK) return;
        accel_reads_++;
        const float v[3] = { s.x_mg, s.y_mg, s.z_mg };
        for (int i = 0; i < 3; i++) {
            if (v[i] < accel_min_[i]) accel_min_[i] = v[i];
            if (v[i] > accel_max_[i]) accel_max_[i] = v[i];
            if (accel_max_[i] - accel_min_[i] > 80.0f) accel_moved_ = true;
        }
        float mag = sqrtf(v[0] * v[0] + v[1] * v[1] + v[2] * v[2]);
        accel_reasonable_ = (mag > 300.0f && mag < 2000.0f); // ~1g present
        if (accel_reads_ >= 3)
            result_[CAT_ACC] = (accel_reasonable_ || accel_moved_) ? Res::Pass : Res::Fail;
    }

    // ---- NFC reader IC handshake (no screen; one-shot) ---------------------

    void probe_nfc_chip()
    {
        if (nfc_chip_probed_) return;
        nfc_chip_probed_ = true;
        result_[CAT_RC522] = (hal_nfc_probe(&nfc_chip_version_) == ESP_OK) ? Res::Pass : Res::Fail;
    }

    // ---- status strip (top of every screen) --------------------------------

    int current_cat() const
    {
        switch (step_) {
            case Step::Buttons: return CAT_BTN;
            case Step::Leds:    return CAT_LED;
            case Step::Nfc:     return CAT_NFC;
            default:            return -1;
        }
    }

    // The strip tracks the three interactive stages. The accelerometer is
    // judged passively and only reported on the summary, not here.
    static constexpr int STRIP_COUNT = CAT_NFC + 1; // BTN, LED, NFC

    void build_status_strip()
    {
        static const char *labels[STRIP_COUNT] = { "BTN", "LED", "NFC" };
        constexpr int n = STRIP_COUNT, w = 74, h = 22, gap = 4, y = 4;
        const int total = n * w + (n - 1) * gap;
        const int x0 = (320 - total) / 2;
        for (int i = 0; i < n; i++) {
            lv_obj_t *c = lv_obj_create(root_);
            lv_obj_remove_style_all(c);
            lv_obj_set_size(c, w, h);
            lv_obj_set_pos(c, x0 + i * (w + gap), y);
            lv_obj_set_style_radius(c, 4, 0);
            lv_obj_set_style_bg_opa(c, LV_OPA_COVER, 0);
            lv_obj_set_style_border_width(c, 2, 0);
            lv_obj_clear_flag(c, LV_OBJ_FLAG_SCROLLABLE);
            lv_obj_t *l = lv_label_create(c);
            lv_label_set_text(l, labels[i]);
            lv_obj_set_style_text_font(l, &lv_font_montserrat_14, 0);
            lv_obj_center(l);
            strip_cells_[i] = c;
        }
        update_strip();
    }

    void update_strip()
    {
        const int cur = current_cat();
        for (int i = 0; i < STRIP_COUNT; i++) {
            lv_obj_t *c = strip_cells_[i];
            if (!c) continue;
            lv_obj_set_style_bg_color(c, lv_color_hex(color_for(result_[i])), 0);
            bool active = (i == cur);
            lv_obj_set_style_border_color(c, lv_color_hex(active ? COL_CURRENT : COL_BORDER), 0);
            lv_obj_t *l = lv_obj_get_child(c, 0);
            if (l) lv_obj_set_style_text_color(l, lv_color_hex(COL_TEXT), 0);
        }
    }

    // ---- per-screen scaffolding -------------------------------------------

    void build_step_ui()
    {
        if (!root_) return;

        // Tear down power-hungry HALs when leaving their screens.
        if (step_ != Step::Nfc && nfc_enabled_) { hal_nfc_disable(); nfc_enabled_ = false; }
        if (step_ != Step::Leds) { hal_lights_clear(); hal_lights_show(); }

        lv_obj_clean(root_);
        for (auto &c : strip_cells_) c = nullptr;
        title_ = info_en_ = info_cn_ = nullptr;
        for (auto &p : pads_) p = nullptr;
        led_en_ = led_cn_ = nfc_status_ = nullptr;

        build_status_strip();

        title_ = make_label(root_, &lv_font_montserrat_20, 0xffffff, "");
        lv_obj_align(title_, LV_ALIGN_TOP_MID, 0, 32);

        switch (step_) {
            case Step::Buttons: build_buttons(); break;
            case Step::Leds:    build_leds();    break;
            case Step::Nfc:     build_nfc();     break;
            case Step::Summary: build_summary(); break;
        }
    }

    // English line then Chinese line, pinned to the bottom.
    void set_info(const char *en, const char *cn)
    {
        info_en_ = make_label(root_, &lv_font_montserrat_16, COL_TEXT, en);
        lv_obj_align(info_en_, LV_ALIGN_BOTTOM_MID, 0, -28);
        info_cn_ = make_label(root_, &font_cjk_18, COL_CURRENT, cn);
        lv_obj_align(info_cn_, LV_ALIGN_BOTTOM_MID, 0, -6);
    }

    // ---- Screen 1: Buttons -------------------------------------------------

    void build_buttons()
    {
        lv_label_set_text(title_, "Buttons");
        set_info("Press every button", "按下所有按钮");

        // Mirror the physical badge and test all nine switches, including
        // SideSwitch and B (B is not navigation in factory-test mode).
        make_pad(Button::Aux1,  52,  72, "SideSwitch", 96);
        make_pad(Button::Up,    82, 105, "UP");
        make_pad(Button::Left,  46, 139, "LEFT");
        make_pad(Button::Right,118, 139, "RIGHT");
        make_pad(Button::Down,  82, 173, "DOWN");
        make_pad(Button::B,    224, 113, "B", 44);
        make_pad(Button::A,    280, 113, "A", 44);
        make_pad(Button::Home, 216, 166, "Home", 60);
        make_pad(Button::Start,280, 166, "Start", 60);
        refresh_pads();
    }

    void make_pad(Button b, int cx, int cy, const char *label, int w = 48)
    {
        constexpr int h = 30;
        lv_obj_t *pad = lv_obj_create(root_);
        lv_obj_remove_style_all(pad);
        lv_obj_set_size(pad, w, h);
        lv_obj_set_pos(pad, cx - w / 2, cy - h / 2);
        lv_obj_set_style_radius(pad, 6, 0);
        lv_obj_set_style_bg_opa(pad, LV_OPA_COVER, 0);
        lv_obj_set_style_border_width(pad, 2, 0);
        lv_obj_clear_flag(pad, LV_OBJ_FLAG_SCROLLABLE);
        lv_obj_t *lbl = lv_label_create(pad);
        lv_label_set_text(lbl, label);
        lv_obj_set_style_text_font(lbl, &lv_font_montserrat_14, 0);
        lv_obj_center(lbl);
        pads_[(int)b] = pad;
    }

    void refresh_pads()
    {
        for (int i = 0; i < (int)Button::COUNT; i++) update_pad((Button)i);
    }

    void update_pad(Button b)
    {
        lv_obj_t *pad = pads_[(int)b];
        if (!pad) return;
        bool seen = buttons_seen_[(int)b];
        lv_obj_set_style_bg_color(pad, lv_color_hex(seen ? COL_PASS : COL_PENDING), 0);
        lv_obj_set_style_border_color(pad, lv_color_hex(seen ? 0xffffff : COL_BORDER), 0);
        lv_obj_t *lbl = lv_obj_get_child(pad, 0);
        if (lbl) lv_obj_set_style_text_color(lbl, lv_color_hex(seen ? 0xffffff : COL_TEXT), 0);
    }

    void handle_button_pad(Button b)
    {
        if ((int)b >= (int)Button::COUNT) return;
        if (buttons_seen_[(int)b]) return;
        buttons_seen_[(int)b] = true;
        update_pad(b);
        if (all_buttons_seen()) { result_[CAT_BTN] = Res::Pass; advance(); }
    }

    bool all_buttons_seen() const
    {
        for (int i = 0; i < (int)Button::COUNT; i++) {
            if (!buttons_seen_[i]) return false;
        }
        return true;
    }

    // ---- Screen 2: LEDs ----------------------------------------------------

    void build_leds()
    {
        lv_label_set_text(title_, "LEDs");
        set_info("A = working   B = broken", "灯光正常按A故障按B");

        led_en_ = make_label(root_, &lv_font_montserrat_24, 0xffffff, "");
        lv_obj_align(led_en_, LV_ALIGN_CENTER, 0, -14);
        led_cn_ = make_label(root_, &font_cjk_18, COL_TEXT, "");
        lv_obj_align(led_cn_, LV_ALIGN_CENTER, 0, 18);

        lights_tick_ = 0;
        led_phase_shown_ = -1;
        led_cycle_done_ = false;
    }

    void tick_leds()
    {
        constexpr uint32_t ticks_per_color = 25; // ~500ms at 20ms tick
        uint32_t phase = (lights_tick_ / ticks_per_color) % 4;
        lights_tick_++;
        // Require at least one full R/G/B/W cycle before A/B can advance.
        if (lights_tick_ >= ticks_per_color * 4) led_cycle_done_ = true;

        uint8_t r = 0, g = 0, b = 0;
        switch (phase) {
            case 0: r = 64;            break;
            case 1: g = 64;            break;
            case 2: b = 64;            break;
            case 3: r = g = b = 64;    break;
        }
        for (size_t i = 0; i < LED_COUNT; i++) hal_lights_set(i, r, g, b);
        hal_lights_show();

        if ((int)phase == led_phase_shown_) return;
        led_phase_shown_ = (int)phase;
        static const char *en[4] = { "Red", "Green", "Blue", "White" };
        static const char *cn[4] = { "红", "绿", "蓝", "白" };
        static const uint32_t col[4] = { 0xff5555, 0x55ff55, 0x5588ff, 0xffffff };
        if (led_en_) {
            lv_label_set_text(led_en_, en[phase]);
            lv_obj_set_style_text_color(led_en_, lv_color_hex(col[phase]), 0);
        }
        if (led_cn_) {
            lv_label_set_text(led_cn_, cn[phase]);
            lv_obj_set_style_text_color(led_cn_, lv_color_hex(col[phase]), 0);
        }
    }

    // ---- Screen 3: NFC -----------------------------------------------------

    void build_nfc()
    {
        lv_label_set_text(title_, "NFC");
        set_info("Scan a card, or A to skip", "扫描任意卡片或按A跳过");

        lv_obj_t *logo = lv_image_create(root_);
        lv_image_set_src(logo, &icon_nfc);
        lv_obj_align(logo, LV_ALIGN_CENTER, 0, -8);

        nfc_status_ = make_label(root_, &lv_font_montserrat_16, COL_UNTESTED, "...");
        lv_obj_align(nfc_status_, LV_ALIGN_CENTER, 0, 44);

        hal_nfc_clear_last_card();
        hal_nfc_enable();
        nfc_enabled_ = true;
    }

    void tick_nfc()
    {
        NfcCard card;
        if (!hal_nfc_last_card(&card)) return;
        result_[CAT_NFC] = Res::Pass;
        advance();
    }

    // ---- Screen 4: Summary -------------------------------------------------

    void build_summary()
    {
        lv_label_set_text(title_, "Summary");
        set_info("A = run again", "按A重新测试");

        // Bilingual category labels; status glyph (OK / X / -) on the left.
        static const char *en[CAT_COUNT] = { "Buttons", "LEDs", "NFC", "Accel", "NFC chip" };
        // NFC / NFC chip have no Chinese label — the CJK subset font has no
        // Latin N/F/C, so it would render as boxes; the English labels suffice.
        static const char *cn[CAT_COUNT] = { "按钮", "灯光", "", "加速度计", "" };
        for (int i = 0; i < CAT_COUNT; i++) {
            int y = 50 + i * 30;
            Res r = result_[i];
            const char *glyph = r == Res::Pass ? LV_SYMBOL_OK
                              : r == Res::Fail ? LV_SYMBOL_CLOSE
                                               : LV_SYMBOL_MINUS;
            lv_obj_t *g = make_label(root_, &lv_font_montserrat_20, color_for(r), glyph);
            lv_obj_set_pos(g, 44, y);

            // Tag the reader-IC row with the version byte it handshook (handy
            // for confirming the exact chip from a factory photo).
            char buf[20];
            const char *en_txt = en[i];
            if (i == CAT_RC522 && r == Res::Pass) {
                snprintf(buf, sizeof(buf), "NFC chip %02X", nfc_chip_version_);
                en_txt = buf;
            }
            lv_obj_t *le = make_label(root_, &lv_font_montserrat_20, COL_TEXT, en_txt);
            lv_obj_set_pos(le, 86, y);

            lv_obj_t *lc = make_label(root_, &font_cjk_18, COL_UNTESTED, cn[i]);
            lv_obj_set_pos(lc, 196, y + 1);
        }
    }

    // ---- state -------------------------------------------------------------

    lv_obj_t *root_ = nullptr;
    lv_timer_t *tick_timer_ = nullptr;
    Step step_ = Step::Buttons;
    Res result_[CAT_COUNT] = {}; // all Res::Pending (== 0)

    lv_obj_t *strip_cells_[CAT_COUNT] = {};
    lv_obj_t *title_ = nullptr;
    lv_obj_t *info_en_ = nullptr;
    lv_obj_t *info_cn_ = nullptr;

    bool buttons_seen_[(int)Button::COUNT] = {};
    lv_obj_t *pads_[(int)Button::COUNT] = {};

    uint32_t lights_tick_ = 0;
    int led_phase_shown_ = -1;
    bool led_cycle_done_ = false;
    lv_obj_t *led_en_ = nullptr;
    lv_obj_t *led_cn_ = nullptr;

    bool nfc_enabled_ = false;
    lv_obj_t *nfc_status_ = nullptr;

    int accel_reads_ = 0;
    float accel_min_[3] = { 1e9f, 1e9f, 1e9f };
    float accel_max_[3] = { -1e9f, -1e9f, -1e9f };
    bool accel_reasonable_ = false;
    bool accel_moved_ = false;

    bool nfc_chip_probed_ = false;
    uint8_t nfc_chip_version_ = 0;
};

} // namespace

// Entry point invoked from app_main when factory.enabled is set. Returns after
// wiring up the timer + dispatcher; the LVGL task keeps the test running.
void factory_test_run()
{
    FactoryTest::instance().run();
}
